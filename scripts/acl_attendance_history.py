#!/usr/bin/env python3
"""亚冠上座的历史对比：机制折减 vs 对手吸引力（2026-10-20 用户质疑后补做）。

核心发现：
  2019 年 国安年票【含】亚冠小组赛（850/950/1200 元，加量不加价）
  2025 年起 所有年票【不含】亚冠（明确公告），亚冠另售联票
  → 亚冠从"年票权益"变成"需额外付费的独立产品"，边际成本 0 → 479-1299 元/4 场

外部数据（已核，来源见 docs/notes/亚冠与中超定级映射.md）：
  2015 亚冠主场 4 场：35,567 / 38,355 / 35,578 / 43,526（vs 全北）= 场均 38,257
  2019 亚冠主场 3 场：43,112（浦和）/ 25,720（武里南雨战）/ 40,555（vs 全北）= 场均 36,462
  2019 中超主场场均：41,801（Transfermarkt）
  2026 中超工体：半程 7 场场均 49,538（全球俱乐部第 32，超巴黎 47,577）；赛季 13 场 47,188
  2026 亚冠 MD1（vs 浦项）：总到场约 13,910（散票 5,476 + 联票到座 6,273 + 组织 1,700）
"""
from __future__ import annotations

import sys

ROWS = [
    # (赛季, 年票含亚冠?, 亚冠场均/总, 中超主场场均, 备注)
    ("2015", "未核实", 38257, None,
     "4 场亚冠：35,567 / 38,355 / 35,578 / 43,526（vs 全北，官方 4.3 万\"一票难求\"）"),
    ("2019", "**含**（小组赛）", 36462, 41801,
     "3 场：43,112（浦和）/ 25,720（武里南·雨战低温）/ 40,555（vs 全北）；年票 850/950/1200 元含亚冠，加量不加价"),
    ("2025", "**不含**", 1797, None,
     "亚冠二级 3 场【散票】1,367/1,865/2,158（场均 1,797）；年票 1000-3000 元不含亚冠，另售 3 场联票 252-1224 元"),
    ("2026", "**不含**", 13910, 47188,
     "MD1 总到场约 13,910（散票 5,476 张）；年票 1000-3000 元不含亚冠，另售 4 场联票 479-1299 元"),
]


def main() -> int:
    print("=" * 104)
    print("亚冠主场上座的历史对比：到底是「对手不吸引人」还是「年票剥离」？")
    print("=" * 104)
    print(f"{'赛季':<6}{'年票含亚冠':<14}{'亚冠主场':>10}{'中超主场':>10}{'亚冠/中超':>10}   备注")
    print("-" * 104)
    for season, inc, acl, csl, note in ROWS:
        ratio = f"{acl / csl:.2f}" if csl else "—"
        print(f"{season:<6}{inc:<14}{acl:>10,}{csl if csl else '—':>10}{ratio:>10}   {note}")

    print("\n【关键对照】")
    print("  · 同一个对手（全北现代）：2019 年工体 40,555 人 ｜ 2025 年 ACL2 场均 1,797 张散票")
    print("  · 同期中超不但没冷，还创历史新高：2026 工体半程场均 49,538（全球俱乐部第 32）")
    print("  · 2019 亚冠/中超 = 0.87 ｜ 2026 亚冠/中超 = 0.29  → 跌 67%，而中超本身在涨")

    print("\n【结论：不是对手不行，是产品变了】")
    print("  1. 2019 年年票含亚冠小组赛 → 2 万名年票持有者「边际成本 0」，4 万人里大部分是自动到场")
    print("  2. 2025 年起年票明确剥离亚冠 → 想看得再掏 479-1299 元（4 场联票）或 199-688 元（单场）")
    print("  3. 所以 2019 的 4 万人 ≠「高付费意愿」，而是「已付费的顺便到场」；")
    print("     2026 的 5,476 张散票才是真实的「额外付费需求」——两者不可直接比较。")

    print("\n【对模型的影响（重要）】")
    print("  · MD1 锚 5,476 已【内含】年票剥离这一机制折减 → 预测本身没错")
    print("  · 但把「等效中超级别 = C」解释成「北京观众觉得全北只有 C 级」，是【归因错误】")
    print("  · 正确说法：在「年票剥离 + 单独售票」的机制下，全北场散票需求 ≈ 中超 C 级；")
    print("    这不等于全北的吸引力是 C 级 —— 2019 年同一对手能来 4 万人。")

    print("\n【真正能测「对手吸引力」的，只有同机制内的对比】")
    print("  2025 ACL2 三场（同为年票剥离）：1,367 / 1,865 / 2,158 → CV 22.3% ≈ 噪声（中超残差 21.3%）")
    print("  2026 ACLE：MD1 浦项 5,476 → MD3 全北预测 6,052（+10.5%，含售期+5%）")
    print("  → 同机制内对手差异确实很小（γ=0.15 的依据成立），但这不是「机制折减」的证据")

    print("\n【摆到桌面上的决策选项】")
    print("  A. 维持现状（年票不含亚冠）：亚冠 4 场收入 ~1,194 万，上座 ~1.4 万/场")
    print("  B. 年票含亚冠（回到 2019 模式）：上座或回到 3.5-4 万，但亚冠票收入归零")
    print("  C. 折中（年票含小组赛、淘汰赛另售 / 年票享深度折扣）：需算弹性，本项目无数据")
    print("  → 建议：本场不改机制（距开赛 7 天），但把 A/B 的对比作为 2027 赛季票务设计输入。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
